def tectonic_subsidence_at_time(
    si_km: float,
    thermal_rate_mm_yr: float,
    tau_ma: float,
    time_ma: float,
) -> float:
    """Tectonic subsidence at time t (m).

    S(t) = Sᵢ + ∫₀ᵗ thermal_rate · exp(-t'/τ) dt'
    S(t) = Sᵢ + thermal_rate · τ · (1 - exp(-t/τ))

    where thermal_rate is in mm/yr and τ is in Myr.
    Unit conversion: 1 mm/yr × 1 Myr = 1000 m.
    """
    si_m = si_km * 1000.0
    # Thermal contribution: integral of exponential decay
    thermal_m = thermal_rate_mm_yr * tau_ma * (1.0 - math.exp(-time_ma / tau_ma))
    return si_m + thermal_m


def sediment_load_isostasy(
    sediment_thickness_m: float,
    rho_sed: float = RHO_SEDIMENT_KGM3,
    rho_water: float = RHO_WATER_KGM3,
    rho_mantle: float = RHO_MANTLE_KGM3,
) -> float:
    """Isostatic subsidence from sediment loading (Airy isostasy).

    ΔS = T_sed × (ρs - ρw) / (ρm - ρw)

    Steckler & Watts (1978), Allen & Allen (2005, eq. 9.17).
    Returns subsidence in meters.
    """
    ratio = (rho_sed - rho_water) / (rho_mantle - rho_water)
    return sediment_thickness_m * ratio


def decompact_thickness(
    present_thickness_m: float,
    depth_km: float,
    phi0: float = PHI0_SAND,
    c_per_km: float = C_SAND_PER_KM,
) -> float:
    """Restore compacted thickness to original depositional thickness.

    Uses Athy (1930) porosity-depth law: φ(z) = φ₀ · exp(-c·z)

    Solid grain thickness is conserved:
      T_solid = T_present × (1 - φ_avg_present)
      T_original = T_solid / (1 - φ₀)
    """
    # Average porosity over the depth interval
    z_top = max(0.0, depth_km - present_thickness_m / 1000.0)
    z_bot = depth_km
    if z_bot <= z_top:
        phi_avg = phi0
    else:
        # Analytical average of exponential over interval
        integral = phi0 / c_per_km * (math.exp(-c_per_km * z_top) - math.exp(-c_per_km * z_bot))
        phi_avg = integral / (z_bot - z_top) if (z_bot - z_top) > 0 else phi0

    solid_fraction = 1.0 - phi_avg
    surface_porosity_fraction = 1.0 - phi0
    if surface_porosity_fraction <= 0:
        return present_thickness_m
    return present_thickness_m * solid_fraction / surface_porosity_fraction


def get_eustatic_level(
    time_ma: float,
    eustatic_curve: list[EustaticPoint] | None = None,
    constant_rate_mm_yr: float = 0.0,
) -> float:
    """Get eustatic sea level at a given time (m).

    If curve provided, linearly interpolates. Otherwise uses constant rate.
    """
    if eustatic_curve and len(eustatic_curve) >= 2:
        # Sort by time (descending = oldest first)
        sorted_pts = sorted(eustatic_curve, key=lambda p: p.time_ma, reverse=True)
        # Find bracketing points
        for i in range(len(sorted_pts) - 1):
            t1, sl1 = sorted_pts[i].time_ma, sorted_pts[i].sea_level_m
            t2, sl2 = sorted_pts[i + 1].time_ma, sorted_pts[i + 1].sea_level_m
            if t1 >= time_ma >= t2:
                # Linear interpolation
                if abs(t1 - t2) < 1e-10:
                    return sl1
                frac = (t1 - time_ma) / (t1 - t2)
                return sl1 + frac * (sl2 - sl1)
        # Extrapolation: use nearest point
        if time_ma > sorted_pts[0].time_ma:
            return sorted_pts[0].sea_level_m
        return sorted_pts[-1].sea_level_m
    else:
        # Constant rate: sea level change = rate × time
        return constant_rate_mm_yr * time_ma


