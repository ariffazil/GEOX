def simulate_accommodation(req: AccommodationRequest) -> AccommodationResult:
    """Run the accommodation simulation.

    At each time step:
    1. Compute tectonic subsidence (McKenzie exponential)
    2. Get eustatic sea level (from curve or constant rate)
    3. Compute accommodation = water_depth + possible sediment
    4. Distribute sediment into accommodation
    5. Compute sediment loading isostasy
    6. Classify surface type and stacking pattern from PHYSICS

    Surfaces and patterns EMERGE — they are not assigned by rules.

    F2 TRUTH: all outputs are DER (derived from physics models).
    F7 HUMILITY: confidence capped at 0.90.
    """
    n_steps = max(2, int(req.duration_ma / req.time_step_myr) + 1)
    dt = req.duration_ma / (n_steps - 1)

    # Lithology params for compaction
    if req.dominant_lithology.lower() in ("shale", "mudstone", "clay"):
        _phi0, _c_per_km = PHI0_SHALE, C_SHALE_PER_KM
    else:
        _phi0, _c_per_km = PHI0_SAND, C_SAND_PER_KM

    steps: list[AccommodationStep] = []
    prev_water_depth = req.initial_water_depth_m
    prev_stacking = StackingPattern.AGGRADATIONAL
    cumulative_sediment = 0.0
    cumulative_subsidence_m = 0.0
    prev_eustatic = get_eustatic_level(
        req.duration_ma,
        req.eustatic_curve,
        req.eustatic_rate_mm_yr,
    )

    # Tracking for MFS detection
    max_water_depth = req.initial_water_depth_m

    for i in range(n_steps):
        t = req.duration_ma - i * dt  # time goes from oldest to youngest

        # 1. Tectonic subsidence at this time
        tect_sub_m = tectonic_subsidence_at_time(
            req.initial_subsidence_km,
            req.thermal_subsidence_rate_mm_yr,
            req.tau_ma,
            t,
        )

        # 2. Eustatic sea level
        eustatic_m = get_eustatic_level(t, req.eustatic_curve, req.eustatic_rate_mm_yr)
        eustatic_m - prev_eustatic

        # 3. Sediment loading isostasy
        sed_load_m = sediment_load_isostasy(cumulative_sediment)

        # 4. Total accommodation
        # Accommodation = space available for sediment above basement
        total_accommodation = tect_sub_m + eustatic_m + sed_load_m

        # 5. Water depth = accommodation - sediment fill
        water_depth = total_accommodation - cumulative_sediment
        water_depth = max(0.0, water_depth)

        # 6. Sediment deposition for this step
        # Sediment fills available accommodation, bounded by supply rate
        available_accommodation = water_depth
        sediment_this_step = min(
            req.sediment_supply_rate_m_myr * dt,
            available_accommodation,
        )
        sediment_this_step = max(0.0, sediment_this_step)

        # 7. Erosion if accommodation is negative (sea-level fall + uplift)
        erosion_this_step = 0.0
        if total_accommodation < cumulative_sediment:
            erosion_this_step = cumulative_sediment - total_accommodation
            cumulative_sediment = total_accommodation

        cumulative_sediment += sediment_this_step
        cumulative_subsidence_m = tect_sub_m

        # 8. Classify surface from PHYSICS
        surface_type = SurfaceType.CONFORMABLE
        is_fs = False
        is_mfs = False
        is_sb = False

        # Erosion surface: accommodation dropped below sediment
        if erosion_this_step > 0.1:
            surface_type = SurfaceType.EROSION
            if erosion_this_step > 1.0:
                surface_type = SurfaceType.SEQUENCE_BOUNDARY
                is_sb = True

        # Flooding surface: water depth increased significantly
        elif water_depth > prev_water_depth + 2.0:
            surface_type = SurfaceType.FLOODING
            is_fs = True

        # Maximum flooding: deepest water
        if water_depth > max_water_depth + 1.0:
            max_water_depth = water_depth
            is_mfs = True
            surface_type = SurfaceType.MAXIMUM_FLOODING

        # Ravinement: flooding + erosion of underlying sediment
        if is_fs and erosion_this_step > 0.05:
            surface_type = SurfaceType.RAVINEMENT

        # 9. Stacking pattern from PHYSICS (not rules)
        stacking = prev_stacking
        if water_depth > prev_water_depth + 1.0:
            stacking = StackingPattern.RETROGRADATIONAL
        elif water_depth < prev_water_depth - 1.0:
            stacking = StackingPattern.PROGRADATIONAL
        elif abs(water_depth - prev_water_depth) <= 1.0:
            stacking = StackingPattern.AGGRADATIONAL
        if erosion_this_step > 1.0:
            stacking = StackingPattern.DEGRADATIONAL

        steps.append(
            AccommodationStep(
                time_ma=round(t, 3),
                tectonic_subsidence_m=round(tect_sub_m, 1),
                eustatic_sea_level_m=round(eustatic_m, 1),
                sediment_thickness_m=round(cumulative_sediment, 1),
                sediment_load_subsidence_m=round(sed_load_m, 1),
                total_accommodation_m=round(total_accommodation, 1),
                water_depth_m=round(water_depth, 1),
                surface_type=surface_type,
                stacking_pattern=stacking,
                is_flooding_surface=is_fs,
                is_maximum_flooding=is_mfs,
                is_sequence_boundary=is_sb,
                erosion_m=round(erosion_this_step, 2),
            )
        )

        prev_water_depth = water_depth
        prev_stacking = stacking
        prev_eustatic = eustatic_m

    # Reverse to chronological order (youngest first = present day)
    steps.reverse()

    # Collect emergent patterns
