    for src_path in (REPO / "apps.json", DOCROOT / "apps.json"):
        if not src_path.exists():
            continue
        try:
            d = json.loads(src_path.read_text())
        except Exception:
            continue
        lst = d.get("apps")
        if isinstance(lst, list):
            return len(lst)
    return None


