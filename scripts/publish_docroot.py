def inject_banner(text: str) -> tuple[str, bool]:
    import re as _re
    # 2026-10-05 FI-008 root-cause fix: the old pattern required ":START -->"
    # verbatim, but v2/v3 markers are annotated ("...START (owned by ...) -->")
    # so it NEVER matched and every publish INSERTED another banner
    # (measured: 3 stacked banners after 3 runs). Tempered block match:
    # from the first CTA comment opening to its first "END -->" (the banner's
    # internal JS holds "END-->" without a space and cannot false-stop).
    pattern = _re.compile(
        r"<!-- EARTH-WITNESS-CTA:(?:(?!END -->).)*?END -->",
        _re.S,
    )
    if pattern.search(text):
        new_text = pattern.sub(BANNER.rstrip(), text, count=1)
        return new_text, new_text != text
    for anchor in ("<body>", "<body ", "<body>"):
        idx = text.find(anchor)
        if idx != -1:
            return text[: idx + len(anchor)] + BANNER + text[idx + len(anchor) :], True
    return text, False

for name in ("index.html",):
    p = DOCROOT / name
    if not p.exists():
        receipt["skipped"].append(f"{name} (missing in docroot)")
        continue
    new_text, changed = inject_banner(p.read_text())
    if changed and not DRY:
        p.write_text(new_text)
    receipt["patched"][f"{name}#ew-cta"] = "injected v2" if changed else "already present"

for name in SYNC:
    src, dst = REPO / name, DOCROOT / name
    if not src.exists():
        receipt["skipped"].append(f"{name} (missing in repo)")
        continue
    if not DRY:
        dst.write_text(src.read_text())
    receipt["synced"].append(name)

for name, subs in PATCHES.items():
    p = DOCROOT / name
    if not p.exists():
        receipt["skipped"].append(f"{name} (missing in docroot)")
        continue
    text = p.read_text()
    before = text
    hits = []
    for pat, rep in subs:
        m = re.search(pat, text)
        if m:
            hits.append(m.group(0))
            text = re.sub(pat, rep, text, count=1)
    if text != before and not DRY:
        p.write_text(text)
    receipt["patched"][name] = hits

print(json.dumps(receipt, indent=1))

# Postcondition: no stale counts left in docroot count-bearing lines
stale = []
for name in ("index.html", "profile.json", "llms.txt", "llms-full.txt", "tools.json"):
    p = DOCROOT / name
    if not p.exists():
        continue
    text = p.read_text()
    for bad in ("31 public MCP tools", "31 governed MCP tools", "42 tools",
                '"mcp_tools": 31', "42 governed"):
        if bad in text:
            stale.append(f"{name}: {bad}")
if stale:
    print("STALE REMNANTS:", stale)
    sys.exit(1)
print(f"POSTCONDITION OK: docroot count-bearing lines all state {N}")
