#!/usr/bin/env python3
"""gen_synthetic_m1_fixtures.py — generate remaining GATE C synthetic fixtures (M1 set).

Deterministic, SYNTHETIC ONLY, no PETRONAS names/coords/wells. No geological validity.
Purpose: schema / adapter / invariants / failure-path testing.

Follows M1_SYNTHETIC_FIXTURE_SPEC.md anti-real markers:
  - 8 wells at exact 2.0 km spacing (synthetic grid)
  - marker ages at round values (5/10/20/30 Ma)
  - uniform structural offset (constant throw)
  - velocity = linear v(z); compaction = textbook Athy defaults

Emits (into fixtures/):
  SYNTHETIC_structure_map.json, SYNTHETIC_well_tops.yaml, SYNTHETIC_orientation.csv,
  SYNTHETIC_velocity.yaml, SYNTHETIC_strat_column.yaml, SYNTHETIC_compaction.yaml,
  SYNTHETIC_datum.yaml

Run: cd /root/GEOX && .venv/bin/python3 scripts/gen_synthetic_m1_fixtures.py
"""

from __future__ import annotations

import csv
import datetime
import json
from pathlib import Path

import numpy as np

BASE = Path("/root/GEOX/fixtures")
SEED = "m1-set-0001"
FAULT_X = 0.0
THROW = 50.0
UNITS = ["SYNTH_TOP_C", "SYNTH_TOP_B", "SYNTH_TOP_A"]  # young -> old


def header(name: str) -> dict:
    return {
        "synthetic": True,
        "generator": "scripts/gen_synthetic_m1_fixtures.py",
        "seed": SEED,
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "purpose": ["schema", "adapter", "invariants", "failure_path"],
        "geological_validity": "NONE",
        "no_petronas": True,
        "component": name,
    }


def write_json(name: str, payload: dict) -> None:
    payload = {**header(name), **payload}
    (BASE / f"SYNTHETIC_{name}.json").write_text(json.dumps(payload, sort_keys=True, indent=2) + "\n")


def write_yaml(name: str, payload: dict) -> None:
    # minimal YAML emitter (no external dep)
    (BASE / f"SYNTHETIC_{name}.yaml").write_text(_yaml(header(name), payload))


def _yaml(hdr: dict, body: dict) -> str:
    lines = ["# SYNTHETIC — generated by scripts/gen_synthetic_m1_fixtures.py", "synthetic: true"]
    for k, v in hdr.items():
        if k == "synthetic":
            continue
        lines.append(f"{k}: {_yv(v)}")
    for k, v in body.items():
        lines.append(f"{k}: {_yv(v)}")
    return "\n".join(lines) + "\n"


def _yv(v):
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, (int, float)):
        return v
    if isinstance(v, list):
        return "[" + ", ".join(_yv(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {_yv(x)}" for k, x in v.items()) + "}"
    return json.dumps(str(v))


def main() -> int:
    rng = np.random.default_rng(int.from_bytes(SEED.encode(), "big") % (2**32))

    # 1. structure map: gridded top-horizon depth (regular grid, uniform throw)
    nx, ny = 40, 40
    x = np.linspace(-4.0, 4.0, nx)
    y = np.linspace(-4.0, 4.0, ny)
    z = np.zeros((ny, nx))
    for i in range(ny):
        for j in range(nx):
            z[i, j] = (THROW if x[j] > FAULT_X else 0.0) + rng.normal(0, 0.3)
    write_json(
        "structure_map",
        {
            "grid": {"x": x.tolist(), "y": y.tolist(), "z": z.tolist()},
            "fault": {"x": FAULT_X, "throw": THROW},
            "uniform_offset": True,
        },
    )

    # 2. well tops: 8 wells at exact 2.0 km spacing + marker ages (round Ma)
    wells = []
    for i in range(8):
        wx = -7.0 + 2.0 * i  # exact 2.0 km spacing
        side = 1 if wx > FAULT_X else 0
        tops = []
        base_depth = side * THROW
        for k, u in enumerate(UNITS):
            tops.append(
                {
                    "unit": u,
                    "md": round(float(base_depth + 500.0 + k * 400.0 + rng.normal(0, 5)), 1),
                    "tvdss": round(float(base_depth + 500.0 + k * 400.0), 1),
                    "age_ma": round(float([5.0, 10.0, 20.0][k]), 1),
                }
            )
        wells.append({"well": f"SYNTH_W{i + 1:02d}", "x_km": float(wx), "side": "hanging" if side else "footwall", "tops": tops})
    write_yaml("well_tops", {"wells": wells, "spacing_km": 2.0, "n_wells": 8})

    # 3. orientation: bedding dip/dip-azimuth per unit (uniform + jitter)
    with open(BASE / "SYNTHETIC_orientation.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["unit", "dip_deg", "dip_azimuth_deg"])
        for u, base_dip in zip(UNITS, [3.0, 5.0, 7.0]):
            w.writerow([u, round(float(base_dip + rng.normal(0, 0.5)), 2), 90])

    # 4. velocity: V0 + k per unit (linear v(z))
    write_yaml(
        "velocity",
        {
            "model": "linear_vz",
            "units": [{"unit": u, "v0_m_s": 1600.0 + i * 200.0, "k_1_s": 0.6 + 0.05 * i} for i, u in enumerate(UNITS)],
        },
    )

    # 5. strat column: unit names + absolute ages (round Ma)
    write_yaml(
        "strat_column",
        {
            "units": [
                {"name": u, "age_top_ma": round(float(a), 1), "age_base_ma": round(float(a) - 5.0, 1)}
                for u, a in zip(UNITS, [5.0, 10.0, 20.0])
            ],
        },
    )

    # 6. compaction: Athy phi0 + c per lithology class (textbook defaults)
    write_yaml(
        "compaction",
        {
            "model": "athy",
            "lithologies": [
                {"class": "sand", "phi0": 0.49, "c_km": 0.27},
                {"class": "shale", "phi0": 0.63, "c_km": 0.51},
                {"class": "carbonate", "phi0": 0.55, "c_km": 0.35},
            ],
        },
    )

    # 7. datum horizon
    write_yaml("datum", {"horizon": "SYNTH_TOP_A", "reference": "flat synthetic datum at z=0", "throw": THROW})

    out = (
        sorted(p.name for p in BASE.glob("SYNTHETIC_*.json") if "2d_line" not in p.name)
        + sorted(p.name for p in BASE.glob("SYNTHETIC_*.yaml"))
        + sorted(p.name for p in BASE.glob("SYNTHETIC_*.csv"))
    )
    print(f"generated {len(out)} fixtures: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
